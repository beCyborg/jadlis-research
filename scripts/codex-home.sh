#!/bin/bash
# Prints the path of an isolated CODEX_HOME for the research Codex calls, creating/refreshing it first.
# Why: `codex exec` otherwise inherits the user's ~/.codex — model_instructions_file (replaces the Codex
# base prompt), global AGENTS.md (e.g. "answer in Russian" → translated quotes break quote matching),
# memories, plugins and MCP servers. Measured 2026-09-30: 7 of 8 English research prompts came back
# 63–75% Cyrillic. Same pattern as /verif's verif-homes/codex-home.
# Usage: CODEX_HOME="$(bash {PLUGIN_ROOT}/scripts/codex-home.sh)" codex exec ...
set -euo pipefail

SRC_HOME="${CODEX_HOME_SOURCE:-$HOME/.codex}"
DST="${JADLIS_RESEARCH_CODEX_HOME:-$HOME/.claude/research-homes/codex}"

if [[ ! -e "$SRC_HOME/auth.json" ]]; then
  echo "codex-home: no $SRC_HOME/auth.json — run \`codex login\`" >&2
  exit 2
fi

mkdir -p "$DST"
# Login is shared, not copied: a copy would fork the refresh token.
[[ -L "$DST/auth.json" ]] || { rm -f "$DST/auth.json"; ln -s "$SRC_HOME/auth.json" "$DST/auth.json"; }
# Seed the model catalog so the first call does not run on fallback metadata when the refresh times out.
[[ -e "$DST/models_cache.json" || ! -e "$SRC_HOME/models_cache.json" ]] || cp "$SRC_HOME/models_cache.json" "$DST/models_cache.json"

# Owned by this script — rewritten on every call so a plugin update reaches them.
cat > "$DST/config.toml" <<'EOF'
# jadlis-research Codex home — web-search worker only. Generated by scripts/codex-home.sh; edits are overwritten.
sandbox_mode = "read-only"
approval_policy = "never"
service_tier = "default"
web_search = "live"

[features]
memories = false

[notice]
hide_full_access_warning = true
EOF

cat > "$DST/AGENTS.md" <<'EOF'
# Web-research worker

You run inside an automated research pipeline. The prompt is the whole task; nobody will answer questions.

- Language: answer in the language the prompt asks for; if it does not say, in the language of the prompt. Quotes stay verbatim in the source's language — never translate a quote.
- Evidence: search the live web for every claim. Each claim carries its source URL and publication date. No claims from memory; if nothing supports a point, say it was not found.
- Sources: prefer primary ones (official docs, filings, papers, vendor pages, the original post). Open the page before citing it; a search snippet is not a source.
- Speed: put independent queries into one search step instead of one query per step; stop once the asked aspects are covered.
- Do not create or edit files and do not run shell commands.
EOF

echo "$DST"
